# ------------------------------------------------------------------------------------------------
# reference (measured) model
# ------------------------------------------------------------------------------------------------
def macro_charge(pkas: list[float], q_max: int, ph: float) -> float:
    """Sequential macro dissociation model. pkas ascending = steps from the +q_max species downward."""
    pk = sorted(pkas)
    logs = [0.0]
    acc = 0.0
    for k, p in enumerate(pk, start=1):
        acc += p
        logs.append(k * ph - acc)
    mx = max(logs)
    w = [10.0 ** (v - mx) for v in logs]
    s = sum(w)
    return sum(wi * (q_max - k) for k, wi in enumerate(w)) / s


def macro_curve(pkas, q_max, grid=GRID):
    return [{"ph": p, "z": round(macro_charge(pkas, q_max, p), 6)} for p in grid]


def crossings(curve: list[dict]) -> list[float]:
    """pH values where a monotone Z(pH) crosses each half-integer level between its ends → macro pKa read-off."""
    z = [r["z"] for r in curve]; ph = [r["ph"] for r in curve]
    hi, lo = z[0], z[-1]
    levels = [m + 0.5 for m in range(math.floor(lo), math.ceil(hi))]
    out = []
    for lv in levels:
        for i in range(len(z) - 1):
            if (z[i] - lv) * (z[i + 1] - lv) <= 0 and z[i] != z[i + 1]:
                t = (z[i] - lv) / (z[i] - z[i + 1])
                out.append(round(ph[i] + t * (ph[i + 1] - ph[i]), 3)); break
    return sorted(out)


def pI_of(curve):
    z = [r["z"] for r in curve]; ph = [r["ph"] for r in curve]
    for i in range(len(z) - 1):
        if z[i] > 0 >= z[i + 1] or z[i] >= 0 > z[i + 1]:
            if z[i] == z[i + 1]:
                return ph[i]
            t = z[i] / (z[i] - z[i + 1]); return round(ph[i] + t * (ph[i + 1] - ph[i]), 3)
    return None


