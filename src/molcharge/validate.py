# reference set A — IUPAC
# ------------------------------------------------------------------------------------------------
def _inchis_for(smiles: str) -> list[str]:
    from rdkit import Chem
    from rdkit.Chem import inchi
    from rdkit import RDLogger
    RDLogger.DisableLog("rdApp.*")
    m = Chem.MolFromSmiles(smiles)
    out = [inchi.MolToInchi(m)]
    m2 = Chem.MolFromSmiles(smiles); Chem.RemoveStereochemistry(m2)
    i2 = inchi.MolToInchi(m2)
    if i2 not in out:
        out.append(i2)
    return out


def _t_ok(t: str) -> bool:
    try:
        return 20.0 <= float(t) <= 30.0
    except ValueError:
        return False


def load_iupac(path: str, names: dict[str, str]) -> dict[str, dict]:
    if not os.path.isfile(path):
        return {}
    want = {}
    for name, smi in names.items():
        for rank, ik in enumerate(_inchis_for(smi)):
            want.setdefault(ik, []).append((name, rank))
    rows: dict[str, list[dict]] = {}
    with open(path, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            for name, rank in want.get(r["InChI"], []):
                rows.setdefault(name, []).append(dict(r, _rank=rank))
    out = {}
    for name, rs in rows.items():
        best_rank = min(r["_rank"] for r in rs)
        usable = [r for r in rs if r["_rank"] == best_rank and not r["cosolvent"].strip()
                  and r["assessment"].strip() in ("Reliable", "Approximate") and _t_ok(r["T"]) and PKA_TYPE.match(r["pka_type"].strip())]
        by_type: dict[str, list[float]] = {}
        for r in usable:
            try:
                v = float(r["pka_value"])
            except ValueError:
                continue
            if -2.0 <= v <= 16.0:
                by_type.setdefault(r["pka_type"].strip(), []).append(v)
        if not by_type:
            continue
        steps = []
        for t, vals in by_type.items():
            m = PKA_TYPE.match(t); cation = bool(m.group(1)); n = int(m.group(2))
            order = -n if cation else n          # …, pKaH2, pKaH1, pKa1, pKa2, … (ascending charge-order index)
            steps.append({"type": t, "order": order, "median": round(statistics.median(vals), 3), "n": len(vals),
                          "min": min(vals), "max": max(vals)})
        steps.sort(key=lambda s: s["median"])   # ascending pKa = the charge ladder from the most-protonated species down
        q_max = sum(1 for s in steps if s["order"] < 0)   # count of cationic (pKaH*) steps = charge of the fully protonated form
        pkas = [s["median"] for s in steps]
        monotone = all(b > a for a, b in zip(pkas, pkas[1:]))   # strictly ascending medians = a proper sequential ladder
        out[name] = {"source": "IUPAC Dissociation-Constants v2.3 (high-confidence), medians of 20–30 °C aqueous rows "
                               "assessed Reliable/Approximate", "steps": steps, "q_max": q_max, "pkas": pkas,
                     "n_rows_usable": len(usable), "stereo_specific_rows": best_rank == 0,
                     "ok": bool(monotone and steps),
                     "note": None if monotone else "non-monotone median set — skipped"}
    return out


# ------------------------------------------------------------------------------------------------
# reference set B — SAMPL6
# ------------------------------------------------------------------------------------------------
def load_sampl6(d: str) -> dict[str, dict]:
    vals = os.path.join(d, "sampl6_pKa_experimental_values.csv")
    smi = os.path.join(d, "sampl6_molecule_ID_and_SMILES.norm.csv")
    if not (os.path.isfile(vals) and os.path.isfile(smi)):
        return {}
    smiles = {}
    with open(smi, newline="", encoding="utf-8") as fh:
        for r in csv.reader(fh):
            if len(r) >= 2 and r[0].startswith("SM"):
                smiles[r[0]] = r[1]
    out = {}
    with open(vals, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            mid = r["Molecule ID"]
            pk = []
            for i in (1, 2, 3):
                v = (r.get(f"pKa{i} mean") or "").strip()
                if v:
                    pk.append({"pka": float(v), "sem": float((r.get(f"pKa{i} SEM") or "0") or 0)})
            if mid in smiles and pk:
                out[mid] = {"smiles": smiles[mid], "pkas": pk, "assay": r.get("Assay Type", ""),
                            "source": "SAMPL6 pKa challenge experimental data (Sirius T3 UV-metric titration)"}
    return out


