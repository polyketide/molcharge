def selftest() -> int:
    ok = 0; bad = 0
    def gate(d, c, extra=""):
        nonlocal ok, bad
        if c: ok += 1; print(f"  PASS  {d}")
        else: bad += 1; print(f"  FAIL  {d}  {extra}")
    print("== validate_reference selftest ==")
    # 1 macro model reduces to HH when steps are far apart (glycine-like: base 9.8, acid 2.3)
    ref = macro_charge([2.3, 9.8], 1, 7.0); hh = cvp.hh_charge([{"kind": "acid", "pka": 2.3}, {"kind": "base", "pka": 9.8}], 0, 7.0)
    gate("1 macro model = independent-site HH for well-separated steps", abs(ref - hh) < 1e-6, f"{ref} vs {hh}")
    # 2 macro model limits
    gate("2 macro limits: Z(-60)=q_max, Z(+60)=q_max-n", abs(macro_charge([2, 9], 1, -60) - 1) < 1e-9 and abs(macro_charge([2, 9], 1, 60) + 1) < 1e-9)
    # 3 crossings read-off recovers the pKa of a synthetic curve
    cur = macro_curve([3.0, 8.0], 1); ro = crossings(cur)
    gate("3 half-integer crossings read off macro pKa (3.0, 8.0) within 0.05", len(ro) == 2 and abs(ro[0] - 3.0) < 0.05 and abs(ro[1] - 8.0) < 0.05, str(ro))
    # 4 pI read-off
    gate("4 pI read-off of a synthetic glycine-like curve ≈ 5.5", abs((pI_of(cur) or 0) - 5.5) < 0.05, str(pI_of(cur)))
    # 5 IUPAC loader (skips if data absent)
    if os.path.isfile(IUPAC_CSV):
        iu = load_iupac(IUPAC_CSV, {"glycine": IUPAC_SET["glycine"], "L-lysine": IUPAC_SET["L-lysine"]})
        g = iu.get("glycine", {})
        gate("5 IUPAC glycine: q_max=1, two steps, medians inside the textbook window (2.2-2.5 / 9.5-9.9)",
             g.get("ok") and g.get("q_max") == 1 and len(g.get("pkas", [])) == 2
             and 2.2 <= g["pkas"][0] <= 2.5 and 9.5 <= g["pkas"][1] <= 9.9, str(g.get("pkas")))
        ly = iu.get("L-lysine", {})
        gate("6 IUPAC lysine: q_max=2, three contiguous ascending steps (~2.2 / 9.1 / 10.8)",
             ly.get("ok") and ly.get("q_max") == 2 and len(ly.get("pkas", [])) == 3
             and 1.9 <= ly["pkas"][0] <= 2.5 and 8.8 <= ly["pkas"][1] <= 9.4 and 10.4 <= ly["pkas"][2] <= 11.1, str(ly.get("pkas")))
        cov = load_iupac(IUPAC_CSV, IUPAC_COVERAGE_SET)
        miss = sorted(n for n in IUPAC_COVERAGE_SET if not cov.get(n, {}).get("ok"))
        gate(f"9 coverage panel: all {len(IUPAC_COVERAGE_SET)} entries load from IUPAC with a usable step ladder", not miss, str(miss))
    else:
        print("  SKIP  5/6/9 IUPAC csv absent:", IUPAC_CSV)
    # 7 SAMPL6 loader
    s6 = load_sampl6(SAMPL6_DIR)
    if s6:
        gate("7 SAMPL6: 24 molecules with SMILES + ≥1 experimental pKa", len(s6) == 24, str(len(s6)))
    else:
        print("  SKIP  7 SAMPL6 files absent in", SAMPL6_DIR)
    # 8 compare_pkas pairing
    m = compare_pkas([3.0, 8.0], [2.5, 8.6, 12.0])
    gate("8 nearest-pKa pairing: deltas −0.5 / +0.6, RMSE 0.552", m["pairs"][0]["delta"] == -0.5 and m["pairs"][1]["delta"] == 0.6 and abs(m["rmse"] - 0.552) < 1e-3, str(m))
    print(f"selftest: {ok}/{ok + bad} passed")
    return 0 if bad == 0 else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="cross-validate charge_vs_ph engines against measured pKa (IUPAC, SAMPL6, literature)")
    ap.add_argument("--engine", default="auto", choices=("auto", "all") + cvp.ENGINES)
    ap.add_argument("--iupac", default=IUPAC_CSV)
    ap.add_argument("--sampl6", default=SAMPL6_DIR)
    ap.add_argument("--extra", default=EXTRA_JSON)
    ap.add_argument("--out", help="STEM → STEM.json + STEM.md")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    rep = run(a.engine, a.iupac, a.sampl6, a.extra)
    md = markdown(rep)
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
        json.dump(rep, open(a.out + ".json", "w"), ensure_ascii=False, indent=1)
        open(a.out + ".md", "w").write(md)
        print(f"written: {a.out}.json {a.out}.md")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
